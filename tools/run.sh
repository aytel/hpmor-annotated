#!/bin/sh
# Полный прогон: из трёх PDF и исходных epub/fb2 собираются книги со сносками.
# Пути задаются переменными HPMOR_SRC (исходники) и HPMOR_OUT (куда класть результат).
set -e
cd "$(dirname "$0")"
P=${PYTHON:-python3}

$P prepare.py           # распаковать epub, достать обложку
$P dump.py              # PDF -> текст страниц
$P dump3.py             # PDF -> текст с метками надстрочных маркеров
$P footnotes.py         # отделить подстрочные сноски печати от основного текста
$P build_hyph.py        # словарь дефисных слов для склейки переносов
$P parse_notes.py       # разобрать раздел «Комментарии» в конце томов
$P join_entries.py      # склеить строки, снять переносы
$P split_quote.py       # разделить цитату и текст комментария
$P build_body.py        # непрерывный текст томов + карта глав и звёздочек
$P locate.py            # найти цитаты в тексте, измерить отступ до звёздочки
$P finalize.py          # точка привязки для каждой записи
$P inline_notes.py      # примечания, уже лежащие в теле электронной книги
$P project.py epub      # перенести привязки в epub
$P project.py fb2       # то же для fb2
$P build_epub.py        # разметка глав, страница примечаний
$P pack_epub.py         # манифест EPUB 3, обложка, сборка архива
$P build_fb2.py         # маркеры и <body name="notes">

$P verify_all.py        # структура и целостность ссылок
$P verify_fb2.py        # fb2 по официальной схеме FictionBook
$P verify_text.py       # текст книги изменился только там, где задумано
