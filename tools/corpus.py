def clean(t):
    t = re.sub(r'\s+', ' ', t).strip()
    t = re.sub(r'\s+([,.;:!?»])', r'\1', t)
    t = re.sub(r'\s*[—–-]\s*Прим\.\s*пер(ев)?\w*\.?$', ' — Прим. перев.', t, flags=re.I)
    t = re.sub(r'\s*[—–-]\s*Прим\.\s*ред\w*\.?$', ' — Прим. ред.', t, flags=re.I)
    t = re.sub(r'\s*[—–-]\s*Прим\.\s*авт\w*\.?$', ' — Прим. авт.', t, flags=re.I)
    return t

def widen(plain, a, b):
    """Вырезаемый кусок тянем влево по пробелам: маркер должен встать вплотную к слову."""
    while a > 0 and plain[a-1].isspace(): a -= 1
    return a, b


def gather(target, CH):
    notes, cuts = [], []          # cuts: (chapter, a, b, replace_with_marker?)
    for o in json.load(open(f"projected_{target}.json")):
        if o["n"] == 108:  continue                      # уедет вместе с эпиграфом
        if o["ins"] is None: continue
        notes.append({"chapter": o["chapter"], "pos": o["ins"], "text": clean(o["comment"]),
                      "src": f'комментарий #{o["n"]}'})
    for n in json.load(open(f"inline_{target}.json")):
        p = CH[n["chapter"]]["plain"]
        block = widen(p, *n["cut"])
        if n["chapter"] == DUP_INLINE_CHAPTER:
            cuts.append((n["chapter"], *block, None))
            if n.get("cut2"): cuts.append((n["chapter"], *widen(p, *n["cut2"]), None))
            continue
        mark = widen(p, *n["cut2"]) if n.get("cut2") else block
        cuts.append((n["chapter"], *mark, "MARKER"))
        if n.get("cut2"): cuts.append((n["chapter"], *block, None))
        notes.append({"chapter": n["chapter"], "pos": mark[0], "text": clean(n["text"]),
                      "src": 'прим. перев. (было врезкой в тексте)', "cut": mark})
    for ch, text in EDITOR_NOTES.items():
        p = CH[ch]["plain"]
        m = re.search(r'Название скрыто', p[:200])
        notes.append({"chapter": ch, "pos": m.end(), "text": clean(text),
                      "src": "прим. ред. (восстановлено из печати)"})
    notes.append({"chapter": 23, "pos": -1, "text": clean(
        [o for o in json.load(open(f"projected_{target}.json")) if o["n"] == 108][0]["comment"]),
        "src": "комментарий #108 (на восстановленный эпиграф)"})
    notes.sort(key=lambda n: (n["chapter"], n["pos"]))
    for i, n in enumerate(notes, 1): n["num"] = i
    num_of = {int(m.group(1)): n["num"] for n in notes
              for m in [re.match(r'комментарий #(\d+)', n["src"])] if m}
    for n in notes:
        m = re.match(r'комментарий #(\d+)', n["src"])
        if not m or int(m.group(1)) not in XREF: continue
        tgt = num_of.get(XREF[int(m.group(1))])
        if not tgt: continue
        n["text"] = XREF_TEXT[int(m.group(1))].format(ref="{{ref:%d}}" % tgt)
    return notes, cuts
